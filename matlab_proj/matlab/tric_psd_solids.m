function [x, ws, wso] = tric_psd_solids(u, pc)
%TRIC_PSD_SOLIDS Общая сетка классов для обеих твёрдых популяций. Владелец: B.
%
%   u, pc — шины входов и параметров
%   x     — J×1, размеры классов, м
%   ws    — J×1, массовые доли твёрдого, пришедшего с водой
%   wso   — J×1, массовые доли твёрдого, пришедшего с нефтью
%
% Питон-оригинал — psd_solids(). Сетка ОБЩАЯ на обе популяции, и это
% принципиально: переток твёрдого из нефти в воду идёт поклассово
% (крупные уходят из нефти первыми), поэтому индексы классов у ws и wso
% обязаны совпадать. Две независимые сетки перепутали бы размеры частиц.
%
% Границы охватывают обе медианы: от min(x50)/30 до max(x50)*30.
% При x50_so = x50 сетка совпадает с tric_psd(x50, ...) побитово,
% и модель вырождается в прежнюю трёхфазную.
%#codegen

[~, J] = tric_dims();

% Распределение твёрдого в нефти по умолчанию наследует водяное:
% нулём (или -1 для флага) отмечено «как у воды».
if u.x50_so > 0
    x50_o = u.x50_so;
else
    x50_o = u.x50;
end
if pc.b_so > 0
    b_o = pc.b_so;
else
    b_o = pc.bs;
end
if pc.rrsb_so < 0
    rrsb_o = pc.rrsb;
else
    rrsb_o = (pc.rrsb_so > 0);
end

d_lo = min(u.x50, x50_o);
d_hi = max(u.x50, x50_o);

% Через 10.^linspace, а не logspace — так надёжнее для codegen.
e = 10 .^ linspace(log10(d_lo/30), log10(d_hi*30), J+1);

x   = sqrt(e(1:end-1) .* e(2:end)).';
ws  = tric_psd_w(e, u.x50, pc.bs, pc.rrsb);
wso = tric_psd_w(e, x50_o,  b_o,   rrsb_o);
end
