function [cap, q, lr] = tric_plug_step(q, lr, inj, travel, Rtr_i, lr0)
%TRIC_PLUG_STEP Шаг плуг-фракции по одной ячейке. Владелец: B.
%
%   q      — 1×J, масса по классам в долях ВОДЯНОГО расхода
%   lr     — 1×J, ln текущего радиуса класса
%   inj    — 1×J, приход из нефти в эту ячейку
%   travel — 1×J, приращение ln r за ячейку, = k0*x^2*R*tau*f_clar
%   Rtr_i  — радиус поверхности кека в этой ячейке, м
%   lr0    — ln(r_i), стартовый радиус
%   cap    — захваченное на кек в этой ячейке, доля расхода
%
% Питон-оригинал — класс Plug. Включается флагом inject_at_interface
% и даёт ОЦЕНКУ СНИЗУ для захвата перетекшего твёрдого: частицы входят
% в водяное кольцо на границе r_i и не перемешиваются, поэтому обязаны
% пройти всю толщину кольца. В основном варианте те же частицы считаются
% размазанными по сечению — это то же допущение о перемешивании, на
% котором стоит вся ячеечная модель.
%
% Радиус ведётся как ln r, а не r: траектории в поле omega^2*r
% мультипликативны, r(t) = r0*exp(k*t), поэтому перемещение за ячейку
% просто прибавляется, усреднение по массе линейно и не переполняется.
%#codegen

% Средний по массе ln r: старое содержимое плюс пришедшее с границы.
tot  = q + inj;
safe = max(tot, 1e-300);              % защита от 0/0 в пустых классах
lr   = (q .* lr + inj * lr0) ./ safe;
q    = tot;

% Продвижение к стенке; дальше поверхности кека уехать нельзя.
wall = log(Rtr_i);
lr   = min(lr + travel, wall);

% Дошедшие до кека — захвачены, класс обнуляется и стартует заново.
done = double(lr >= wall - 1e-15);
cap  = sum(q .* done);
q    = q .* (1 - done);
lr   = lr .* (1 - done) + lr0 * done;
end
