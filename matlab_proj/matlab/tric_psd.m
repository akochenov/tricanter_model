function [x, w] = tric_psd(d50, b, rrsb)
%TRIC_PSD Классы дисперсной фазы и их массовые доли. Владелец: B.
%
%   d50  — медиана, м
%   b    — параметр формы
%   rrsb — true: RRSB, false: сигмоида
%   x    — J×1, размеры классов (среднее геометрическое границ), м
%   w    — J×1, массовые доли, sum(w) = 1
%
% ЗАГЛУШКА: равномерное распределение. Эталон: ref/psd_solids_*.csv,
% ref/psd_drops_*.csv. Питон-оригинал — функция psd().
%
% Реализовать: логарифмически равномерная сетка от d50/30 до d50*30
% (J+1 граница), кумулята Q3, w = diff(Q3), нормировка.
%#codegen

[~, J] = tric_dims();

% Границы классов: логарифмически равномерно, от d50/30 до d50*30.
% Пишу через 10.^linspace, а не logspace — гарантированно
% поддерживается codegen и даёт то же самое.
e = 10 .^ linspace(log10(d50/30), log10(d50*30), J+1);

% Кумулятивная массовая доля Q3 на границах
if rrsb
    Q3 = 1 - exp(-(e ./ d50) .^ b);       % Розин–Раммлер
else
    Q3 = 1 ./ (1 + (d50 ./ e) .^ b);      % сигмоида
end

% Класс = среднее геометрическое границ, доля = приращение кумуляты
x = sqrt(e(1:end-1) .* e(2:end)).';
w = diff(Q3).';
w = w / sum(w);
% x = d50 * ones(J,1);
% w = ones(J,1) / J;
end
