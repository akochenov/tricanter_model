function [moved, phi_so_next, phi_so_out] = tric_cascade_solids_oil(phi_so, geo, u, pc, dt)
%TRIC_CASCADE_SOLIDS_OIL Осаждение твёрдого, пришедшего внутри нефти. Владелец: B.
%
%   phi_so      — n×J, концентрации с предыдущего шага (СОСТОЯНИЕ)
%   geo, u, pc  — шины
%   dt          — шаг по времени, с
%   moved       — n×J, ПОКЛАССОВО захваченное на границу r_i, в долях
%                 нефтяного расхода; уходит в водяное кольцо той же ячейки
%   phi_so_next — n×J, концентрации на следующий шаг
%   phi_so_out  — доля твёрдого в нефтяном продукте
%
% Третья дисперсная популяция, её не было в прежней модели. Кольцо
% Ro .. r_i, несущая — НЕФТЬ, захват на границу раздела.
%
% Зачем она нужна: осаждение твёрдого в нефти примерно в 28 раз медленнее,
% чем в воде — (rho_s-rho_o)/eta_o против (rho_s-rho_w)/eta_w. Именно эта
% популяция и определяет мехпримеси в нефтяном продукте. Без неё модель
% структурно выдаёт абсолютно чистую нефть при любом режиме.
%
% moved возвращается ПОКЛАССОВО, а не суммой: переток через границу идёт
% по классам, крупные частицы уходят из нефти первыми. Поэтому же сетка
% классов общая с водяной популяцией — см. tric_psd_solids.
%
% Опорная концентрация здесь phi_ref (твёрдое), а не phi_max: phi_max
% относится к плотной упаковке КАПЕЛЬ и живёт в tric_cascade_drops.
%#codegen

[n, J] = tric_dims();

if ~geo.oil
    % Нефтяного кольца нет — оседать негде. Состояние не обновляется,
    % на выход идёт входная концентрация (проскок).
    moved       = zeros(n, J);
    phi_so_next = phi_so;
    phi_so_out  = geo.phi_so0;
    return
end

% Классы общие с водяным твёрдым, доли — свои.
[xs, ~, wso] = tric_psd_solids(u, pc);

% Кольцо нефти от кека не зависит, поэтому tau одинаково во всех ячейках.
% Раздуть до n×1 обязательно: grade и settle_dyn ждут вектор по ячейкам.
tau_o = (pi * (geo.r_i^2 - u.Ro^2) * geo.Lax / geo.Qo) * ones(n, 1);

% Несущая — нефть. eta_o из ВХОДОВ, не eta_w из параметров.
k_so = (pc.rho_s - pc.rho_o) * geo.omega^2 / (18 * u.eta_o);

% Префактор через r_i: внешняя стенка кольца для этой популяции —
% граница раздела, а не барабан.
pref_o = geo.r_i^2 / max(geo.r_i^2 - u.Ro^2, 1e-12);

T_so = tric_grade(xs, k_so, tau_o * geo.f_clar, pref_o, phi_so, pc.phi_ref);

% Подсыпать сюда нечего — популяция питается только подачей.
[~, moved, phi_so_next] = tric_settle_dyn(geo.phi_so0, wso, zeros(n, J), ...
                                          T_so, phi_so, tau_o, dt);

phi_so_out = sum(phi_so_next(end, :));
end
