function T_mat = tric_grade(x, k0, tau, pref, phi_cells, phi_ref)
%TRIC_GRADE Матрица эффективности захвата по ячейкам и классам. Владелец: B.
%
%   x         — J×1, размеры классов, м
%   k0        — стоксова константа без x^2, 1/(м^2·с)
%   tau       — n×1, время пребывания (уже умноженное на f_clar), с
%   pref      — префактор кольца (по ФИКСИРОВАННОЙ границе, не по Rtr)
%   phi_cells — n×J, текущие концентрации по ячейкам (СОСТОЯНИЕ)
%   phi_ref   — опорная доля для Ричардсона-Заки
%   T_mat     — n×J, доля захвата
%
% Питон-оригинал — функция grade(), три строки. Эталон:
% ref_dyn/step1_Ts_*.csv (пустая машина, стеснение неактивно).
%
% T(i,j) — вероятность частице класса j осесть в ячейке i. НЕ кумулятивна
% и не имеет отношения ни к E_s_i, ни к E_s; см. CONTRACT.md.
%#codegen

% --- множитель стеснения Ричардсона-Заки, n×1 ---
% Сумма идёт ПО КЛАССАМ: в питоне phi_cells.sum(1), то есть ось 1,
% в MATLAB это sum(...,2). Перепутать оси — молча получить n вместо J.
% На step1 концентрации нулевые и R == 1, поэтому этот множитель можно
% вообще не написать и step1 всё равно сойдётся. Ловится только на steady.
R = max(0, 1 - sum(phi_cells, 2) / phi_ref) .^ 4.65;

% --- аргумент экспоненты, n×J ---
% Внешнее произведение столбца (R.*tau) на строку 2*k0*x.^2. Записано
% матричным умножением, а не неявным расширением: codegen выводит
% фиксированный размер, и группировка множителей та же, что в питоне.
arg = (R .* tau) * ((2*k0) * (x.^2)).';

% --- точная форма с экспонентой, НЕ линеаризация Gleiss ---
T_mat = min(1, pref * (1 - exp(-arg)));
end
