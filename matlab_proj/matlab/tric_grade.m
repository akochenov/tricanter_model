function T_mat = tric_grade(x, k0, tau, pref, phi_cells, phi_ref)
%TRIC_GRADE Матрица эффективности захвата по ячейкам и классам. Владелец: B.
%
%   x         — J×1, размеры классов, м
%   k0        — стоксова константа без x^2, 1/(м^2·с)
%   tau       — n×1, время пребывания (уже умноженное на f_clar), с
%   pref      — префактор кольца (по ФИКСИРОВАННОЙ границе, не по Rtr)
%   phi_cells — n×J, текущие концентрации по ячейкам (СОСТОЯНИЕ)
%   phi_ref   — опорная доля для Ричардсона-Заки
%   T_mat     — n×J, доля захвата
%
% ЗАГЛУШКА: захвата нет.
% Эталон: ref_dyn/step1_Ts_*.csv (матрица 25×40 для пустой машины).
%
% Питон-оригинал — функция grade(). Формулы:
%   R     = max(0, 1 - sum(phi_cells,2)/phi_ref).^4.65      n×1
%   k     = k0 * x.^2                                        1×J
%   T_mat = min(1, pref*(1 - exp(-2*k.*R.*tau)))            n×J
%
% КРИТИЧНО: точная форма с exp, НЕ линеаризация Gleiss. И pref по Rd
% (для твёрдого) либо по r_i (для капель) — при подстановке Rtr модель
% теряет самоограничение, см. §1 документа постановки.
%#codegen

[n, J] = tric_dims();
T_mat  = zeros(n, J);
end
