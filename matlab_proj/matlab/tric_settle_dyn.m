function [cap, cap_mat, phi_next] = tric_settle_dyn(phi0, w, inj, T_mat, phi_prev, tau, dt)
%TRIC_SETTLE_DYN Шаг каскада с концентрациями-состояниями. Владелец: B.
%
%   phi0     — объёмная доля дисперсной фазы на входе в машину
%   w        — J×1, массовые доли классов
%   inj      — n×J, приход в ячейку извне каскада (переток из нефти);
%              нули для популяций, которым ниоткуда не подсыпают
%   T_mat    — n×J, эффективность захвата (из tric_grade)
%   phi_prev — n×J, концентрации с предыдущего шага (СОСТОЯНИЕ)
%   tau      — n×1, время пребывания по ячейкам, БЕЗ f_clar, с
%   dt       — шаг по времени, с
%   cap      — n×1, захват по ячейкам в долях расхода
%   cap_mat  — n×J, то же по классам (нужно для перетока: он поклассовый)
%   phi_next — n×J, концентрации на следующий шаг
%
% Общий каскад для всех трёх дисперсных популяций: твёрдое в воде,
% твёрдое в нефти, капли воды в нефти. Различаются они только тем,
% какие T_mat, tau и inj им подать.
%
% РЕДАКЦИЯ КАСКАДА. Вход ячейки берётся с ТЕКУЩЕГО шага,
% up = phi_next(c-1,:) + inj(c,:), а не с прошлого. Осевого запаздывания
% на шаг сетки нет — оно уже сидит в tau внутри экспоненты, и сдвиг
% на прошлый шаг добавлял бы к нему лишние n*dt секунд чисто численного
% происхождения. Отсюда прогонка по ячейкам: ячейка c зависит от c-1.
%
% Эталоны в ref_dyn/ выгружены под эту редакцию при frac_s_in_oil = 0.
% Если вернуть старую векторную схему, steady пройдёт, а step1 развалится.
% См. REDACTION_B.md.
%
% Уравнение внутри ячейки линейное, поэтому по времени интегрируется
% ТОЧНО. Схема безусловно устойчива по концентрациям; шаг модели в целом
% ограничен явным Эйлером на массе кека (порядка 4.5 с).
%
% ОТСТУПЛЕНИЕ ОТ ПИТОНА НА ОДИН УЛЬП. Здесь star = up.*(1-T) для всех трёх
% популяций. В питоне так записаны водяное кольцо и капли, а у твёрдого
% в нефти стоит star = up_so - moved. Величины совпадают с точностью
% до последнего разряда; на порог тестов (1e-12) это не влияет.
%#codegen

[n, J] = tric_dims();

% Кламп по tau обязателен: tau_s обращается в нуль, когда кек дорос
% до r_i. У нефтяного кольца tau порядка секунд и кламп не срабатывает.
decay = exp(-dt ./ max(tau, 1e-9));

cap      = zeros(n, 1);
cap_mat  = zeros(n, J);
phi_next = zeros(n, J);

% Вход первой ячейки — свежая подача, разложенная по классам.
up = (phi0 * w).' + inj(1, :);

for c = 1:n
    if c > 1
        % Вход ячейки — уже обновлённое содержимое предыдущей
        % плюс то, что подсыпали из нефтяного кольца.
        up = phi_next(c-1, :) + inj(c, :);
    end

    Tc = T_mat(c, :);

    cap_mat(c, :) = up .* Tc;
    cap(c)        = sum(cap_mat(c, :));

    % star — то, к чему стремится ячейка: прошедшее мимо захвата.
    star = up .* (1 - Tc);
    phi_next(c, :) = star + (phi_prev(c, :) - star) * decay(c);
end
end
