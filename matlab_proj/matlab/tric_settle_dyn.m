function [cap, phi_next] = tric_settle_dyn(phi0, w, T_mat, phi_prev, tau, dt)
%TRIC_SETTLE_DYN Шаг каскада с концентрациями-состояниями. Владелец: B.
%
%   phi0     — объёмная доля дисперсной фазы на входе в машину
%   w        — J×1, массовые доли классов
%   T_mat    — n×J, эффективность захвата (из tric_grade)
%   phi_prev — n×J, концентрации с предыдущего шага (СОСТОЯНИЕ)
%   tau      — n×1, время пребывания по ячейкам, с
%   dt       — шаг по времени, с
%   cap      — n×1, захват по ячейкам В ДОЛЯХ РАСХОДА (не нормированный!)
%   phi_next — n×J, концентрации на следующий шаг
%
% ПОКА_ЗАГЛУШКА: ничего не происходит, состояние не меняется.
% Эталон: ref_dyn/step1_phis_next_*.csv, steady_step_phis_next_*.csv,
%         колонка cap_s в ref_dyn/step1_vec_*.csv.
%
% cap — это НЕ E_s_i. E_s_i = cap ./ (сколько вошло в ячейку) и считается
% один раз в tric_outputs. Вдоль машины cap падает в тысячи раз, E_s_i —
% в десяток. Путать нельзя: cap идёт в баланс кека как rho_s*Qw*cap.
%
% ФОРМУЛЫ. Прогонка по ячейкам СВЕРХУ ВНИЗ, i = 1..n:
%
%   up            = phi0*w.'                    для i = 1
%   up            = phi_next(i-1,:)             для i > 1
%   cap(i)        = sum(up .* T_mat(i,:))
%   star          = up .* (1 - T_mat(i,:))
%   phi_next(i,:) = star + (phi_prev(i,:) - star) * exp(-dt/max(tau(i),1e-9))
%
% Ключевое: вход ячейки i берётся из phi_next(i-1), то есть с ТЕКУЩЕГО
% шага, а не с предыдущего. Поэтому цикл, а не векторная запись через
% сдвиг [phi0*w.'; phi_prev(1:end-1,:)] — так было в старой редакции
% питона, и так делать НЕЛЬЗЯ: сдвиг добавлял к физическому запаздыванию
% паразитное, ровно n*dt секунд, из-за чего переходный процесс зависел
% от шага решателя. Исправлено в питоне, эталоны перевыгружены.
%
% phi_prev входит дважды и по-разному: через up — сдвинутым на ячейку
% (и уже обновлённым), в последнем слагаемом — своей строкой без сдвига.
% Это не опечатка.
%
% Уравнение линейное, поэтому на шаге интегрируется ТОЧНО: схема
% безусловно устойчива и не ограничивает шаг решателя. При dt >> tau
% она сама вырождается в квазистатику.
%
% tau здесь ГОЛЫЙ, без f_clar — экспонента затухания идёт по реальному
% времени пребывания. Домноженный на f_clar уходит только в tric_grade.
%
% ЛОВУШКА ПРИ ОТЛАДКЕ: если написать старую векторную схему, тест steady
% пройдёт, а step1 провалится в разы. Установившийся режим у обеих схем
% совпадает до последнего бита — расходятся только переходные режимы.
% Так что «steady ок, step1 провал» означает именно эту ошибку, а не
% опечатку в формуле.
%#codegen

[n, J] = tric_dims();

cap      = zeros(n, 1);
phi_next = phi_prev;
end