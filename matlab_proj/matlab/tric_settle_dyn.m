function [cap, phi_next] = tric_settle_dyn(phi0, w, T_mat, phi_prev, tau, dt)
%TRIC_SETTLE_DYN Шаг каскада с концентрациями-состояниями. Владелец: B.
%
%   phi0     — объёмная доля дисперсной фазы на входе в машину
%   w        — J×1, массовые доли классов
%   T_mat    — n×J, эффективность захвата (из tric_grade)
%   phi_prev — n×J, концентрации с предыдущего шага (СОСТОЯНИЕ)
%   tau      — n×1, время пребывания по ячейкам, БЕЗ f_clar, с
%   dt       — шаг по времени, с
%   cap      — n×1, захват по ячейкам в долях расхода
%   phi_next — n×J, концентрации на следующий шаг
%
% Питон-оригинал — тело цикла по ячейкам в simulate_dyn, редакция
% "tricanter3 (1).py" (строки 213-222 для твёрдого, 231-238 для капель).
%
% РЕДАКЦИЯ КАСКАДА. Вход ячейки берётся с ТЕКУЩЕГО шага: up = phi_next(c-1,:),
% а не с прошлого. Осевого запаздывания на шаг сетки нет — оно уже сидит
% в tau внутри экспоненты, и сдвиг на прошлый шаг добавлял бы к нему лишние
% n*dt секунд чисто численного происхождения. Отсюда прогонка по ячейкам:
% векторно это не считается, ячейка c зависит от результата ячейки c-1.
%
% Эталоны в ref_dyn/ перевыгружены под эту редакцию, сверка прямая на обоих
% уровнях. Старая векторная редакция (up = phi_prev(c-1,:)) даёт другие числа
% на переходном участке и валит step1; установившийся режим у обеих редакций
% совпадает, поэтому steady такую подмену не ловит. См. REDACTION_B.md.
%
% Уравнение внутри ячейки линейное, поэтому по времени интегрируется ТОЧНО:
% phi_next = star + (phi_prev - star)*exp(-dt/tau). Схема безусловно
% устойчива по концентрациям и при dt >> tau вырождается в квазистатику.
% Шаг модели в целом ограничен не этим, а явным Эйлером на массе кека.
%#codegen

[n, J] = tric_dims();

% Кламп по tau обязателен: tau_s обращается в нуль, когда кек дорос до r_i.
% У капель tau_o порядка секунд и кламп не срабатывает никогда, так что
% одна реализация годится для обеих фаз.
decay = exp(-dt ./ max(tau, 1e-9));

cap      = zeros(n, 1);
phi_next = zeros(n, J);

% Вход первой ячейки — свежая подача, разложенная по классам.
up = (phi0 * w).';

for c = 1:n
    Tc = T_mat(c, :);

    cap(c) = sum(up .* Tc);

    % star — то, к чему ячейка стремится: прошедшее мимо захвата.
    star_c = up .* (1 - Tc);
    phi_next(c, :) = star_c + (phi_prev(c, :) - star_c) * decay(c);

    % Вход следующей ячейки — уже обновлённое содержимое текущей.
    up = phi_next(c, :);
end
end
