function w = tric_psd_w(e, d50, b, rrsb)
%TRIC_PSD_W Массовые доли классов на ЗАДАННОЙ сетке границ. Владелец: B.
%
%   e    — 1×(J+1), границы классов, м
%   d50  — медиана, м
%   b    — параметр формы
%   rrsb — true: Розин–Раммлер, false: сигмоида
%   w    — J×1, массовые доли, sum(w) = 1
%
% Питон-оригинал — psd_weights(). Вынесено отдельно от tric_psd,
% потому что двум твёрдым популяциям нужны разные доли на ОДНОЙ сетке.
%#codegen

if rrsb
    Q3 = 1 - exp(-(e ./ d50) .^ b);       % Розин–Раммлер
else
    Q3 = 1 ./ (1 + (d50 ./ e) .^ b);      % сигмоида
end

w = diff(Q3).';
w = w / sum(w);
end
