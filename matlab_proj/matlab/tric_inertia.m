function [J_load, K_pre, M_scroll] = tric_inertia(m, Rtr, geo, u, pc)
%TRIC_INERTIA Механическая нагрузка на привод барабана. Владелец: A.
%
%   m      — n×1, масса кека по ячейкам, кг
%   Rtr    — n×1, радиус поверхности кека, м
%   J_load   — момент инерции СОДЕРЖИМОГО барабана, кг·м²
%   K_pre    — поток момента импульса на сливах, кг·м²/с
%   M_scroll — момент сопротивления транспорту кека, Н·м
%
% Обе величины нужны подсистеме привода:
%   J_total  = J_bowl + J_load       <- J_bowl из DriveParams, это железо
%   M_pre    = K_pre * omega         <- момент на раскрутку подаваемого потока
%   M_scroll                         <- нагрузка на привод ШНЕКА, готовый Н·м
%
% Разделение такое: здесь всё, что зависит от состояния и геометрии;
% в DriveParams — только то, что относится к самому барабану.
% Тогда при смене типоразмера машины подсистема привода не правится.
%
% МАСШТАБ. Для лабораторной MD80 (Rd = 0.04) обе величины пренебрежимо
% малы: M_pre ~ 1e-5 Н·м против 0.5 Н·м холостого хода, J_load/J_bowl
% меньше процента. Для машины Rd ~ 1 м картина обратная: M_pre порядка
% кН·м и становится основной статьёй нагрузки, а J_load сравнимо с
% моментом инерции самого барабана. Поэтому считается всегда.
%
% Момент инерции кольца R_in..R_out массой M:  J = M*(R_out^2 + R_in^2)/2
%
% ДОПУЩЕНИЯ:
%   - твёрдое, взвешенное в водяном кольце, отнесено к воде (phi ~ 0.06,
%     поправка единицы процентов);
%   - вклад кека в поток момента импульса не учтён: массовый расход кека
%     мал против жидких сливов, а радиус выгрузки в конусе не определён;
%   - жидкость на входе считается поступающей с нулевой окружной
%     скоростью, зоны предускорения нет.
%#codegen

n = tric_dims();

% --- кек: кольцо Rtr..Rd, масса известна напрямую из состояния ---
J_cake = sum(m .* (pc.Rd^2 + Rtr.^2)) / 2;

% --- вода: кольцо r_i..Rtr, сжимается по мере роста кека ---
V_w = pi * max(Rtr.^2 - geo.r_i^2, 0) * geo.Lax;
m_w = pc.rho_w * V_w;
J_w = sum(m_w .* (Rtr.^2 + geo.r_i^2)) / 2;

% --- нефть: кольцо Ro..r_i, от кека не зависит, одинаково по ячейкам ---
V_o = pi * max(geo.r_i^2 - u.Ro^2, 0) * geo.Lax;
m_o = pc.rho_o * V_o;
J_o = n * m_o * (geo.r_i^2 + u.Ro^2) / 2;

J_load = J_cake + J_w + J_o;

% --- поток момента импульса, уносимый сливами ---
% Жидкость входит по оси с нулевой окружной скоростью и уходит на
% радиусе слива, унося omega*R^2 на единицу массы. Отсюда момент,
% который двигатель обязан прикладывать постоянно: M_pre = K_pre*omega.
% Радиусы сливов, НЕ Rd: по Rd получится завышение в (Rd/Rw)^2 раз.
K_pre = pc.rho_w * geo.Qw * u.Rw^2 + pc.rho_o * geo.Qo * u.Ro^2;

% --- момент сопротивления транспорту кека (нагрузка привода шнека) ---
% Кек прижат к стенке центробежной силой F_n = m*omega^2*r_c. Чтобы
% двигать его вдоль оси, надо преодолеть трение о стенку: F_ax = mu_s*F_n.
% Перевод осевой силы в момент на радиусе r_c — обычная механика винта:
%     M = F_ax * r_c * (tan(beta) + mu_s) / (1 - mu_s*tan(beta))
% По формуле тангенса суммы дробь равна tan(arctan(mu_s) + beta) = tan(kappa),
% то есть тому же углу транспортировки, через который считается u_ax.
% Оба места опираются на одну силовую картину, это не совпадение.
%
% От Delta_omega момент НЕ зависит: трение кулоновское, от скорости
% скольжения не зависит. Через Delta_omega зависит мощность P2 = M_scroll*dw
% и, с большим запаздыванием, сама масса кека: быстрее шнек -> больше u_ax
% -> меньше m -> меньше M_scroll. Эта связь замыкается через ядро.
kappa    = atan(pc.mu_s) + geo.beta;
r_c      = (pc.Rd + Rtr) / 2;
M_scroll = abs(pc.mu_s * geo.omega^2 * sum(m .* r_c.^2) * tan(kappa));
end